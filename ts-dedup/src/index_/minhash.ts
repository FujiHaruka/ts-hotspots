/**
 * MinHash signature builder.
 *
 * For each fragment we produce a fixed-length integer signature whose
 * Hamming similarity (positions where two signatures agree) approximates
 * the Jaccard similarity of the two underlying feature sets. The estimator
 * is unbiased: `E[matches / k] = J(A, B)` for k independent hash functions.
 *
 * Implementation strategy: derive `k` independent hashes from a single
 * 32-bit base hash via the "linear combination" trick
 * `h_i(x) = (a_i * baseHash(x) + b_i) mod 2^32`, where `(a_i, b_i)` are
 * drawn from a seeded PRNG. Empirically this produces near-pairwise-
 * independent hashes at a fraction of the cost of hashing each key k times.
 *
 * Pure / deterministic given fixed `seed` and `numHashes`.
 */

import { nonNull } from "../util/nonNull.ts";

const UINT32_MAX = 0xffffffff;

export interface MinHashSignature {
  /** Length = `numHashes`. */
  readonly values: Uint32Array;
}

export interface MinHasher {
  readonly numHashes: number;
  /**
   * Compute a MinHash signature over the feature set. Order-independent.
   * Empty input returns a signature filled with `UINT32_MAX`.
   */
  sign(features: Iterable<string>): MinHashSignature;
}

/**
 * Build a MinHasher with `numHashes` independent hash functions.
 *
 * The internal `(a_i, b_i)` table is generated by a small splitmix32 PRNG
 * seeded with `seed`. Two MinHashers built with the same `(numHashes,
 * seed)` produce bit-identical signatures.
 */
export function createMinHasher(numHashes: number, seed: number): MinHasher {
  if (numHashes <= 0) {
    throw new Error(`numHashes must be > 0 (got ${String(numHashes)})`);
  }
  // Pre-generate (a, b) coefficients. `a` is forced odd (so the linear
  // combination is a permutation modulo 2^32 when treated as a multiplier).
  const aCoeff = new Uint32Array(numHashes);
  const bCoeff = new Uint32Array(numHashes);
  let state = seed >>> 0;
  for (let i = 0; i < numHashes; i++) {
    state = splitmix32(state);
    aCoeff[i] = state | 1;
    state = splitmix32(state);
    bCoeff[i] = state;
  }

  function sign(features: Iterable<string>): MinHashSignature {
    const values = new Uint32Array(numHashes);
    values.fill(UINT32_MAX);
    let any = false;
    for (const feature of features) {
      any = true;
      const base = fnv1a32(feature);
      for (let i = 0; i < numHashes; i++) {
        const a = nonNull(aCoeff[i]);
        const b = nonNull(bCoeff[i]);
        const h = (Math.imul(a, base) + b) >>> 0;
        if (h < nonNull(values[i])) {
          values[i] = h;
        }
      }
    }
    // Empty input: leave all slots at UINT32_MAX. `any` kept for parity
    // with future "skip empty" optimizations.
    void any;
    return { values };
  }

  return { numHashes, sign };
}

/**
 * Estimated Jaccard similarity between two signatures.
 *
 * Returns the fraction of positions where the two signatures agree. For
 * signatures built with the same hash family this is an unbiased estimator
 * of `J(A, B)`. Used by tests; the LSH path doesn't need it (it works on
 * banding collisions, not direct distance).
 */
export function estimatedJaccard(
  a: MinHashSignature,
  b: MinHashSignature,
): number {
  if (a.values.length !== b.values.length) {
    throw new Error("signature length mismatch");
  }
  if (a.values.length === 0) return 0;
  let agree = 0;
  for (let i = 0; i < a.values.length; i++) {
    if (a.values[i] === b.values[i]) agree += 1;
  }
  return agree / a.values.length;
}

/** 32-bit FNV-1a hash. Stable across runs and platforms. */
function fnv1a32(s: string): number {
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i) & 0xff;
    h = Math.imul(h, 0x01000193);
    // Pull in the high byte too — feature keys often share long ASCII
    // prefixes, mixing both bytes spreads the distribution.
    const hi = (s.charCodeAt(i) >> 8) & 0xff;
    if (hi !== 0) {
      h ^= hi;
      h = Math.imul(h, 0x01000193);
    }
  }
  return h >>> 0;
}

/** splitmix32: small high-quality 32-bit PRNG. */
function splitmix32(x: number): number {
  let z = (x + 0x9e3779b9) >>> 0;
  z = Math.imul(z ^ (z >>> 16), 0x21f0aaad) >>> 0;
  z = Math.imul(z ^ (z >>> 15), 0x735a2d97) >>> 0;
  return (z ^ (z >>> 15)) >>> 0;
}
